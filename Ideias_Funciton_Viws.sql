CREATE FUNCTION FC_ORDEM_SERVICO_MEDIA ( @DataInicio DATE, @DataFim DATE)
RETURNS DECIMAL(12,2)
AS
BEGIN
    DECLARE @media DECIMAL(12,2);

    SELECT @media = ISNULL(CAST(AVG(VALOR) AS DECIMAL(12,2)), 0)
    FROM   ORDENS_SERVICOS
    WHERE  STATUS = 3   -- somente OS concluídas
      AND  (@DataInicio IS NULL OR COALESCE(DATA_EXECUCAO, DATA_ABERTURA) >= @DataInicio)
      AND  (@DataFim    IS NULL OR COALESCE(DATA_EXECUCAO, DATA_ABERTURA) <= @DataFim);

    RETURN @media;
END
GO


--ODERM DE SERVIÇO POR STATUS
CREATE VIEW VW_OS_POR_STATUS
AS
SELECT      COUNT(OS.COD_OS) AS TOTAL_ORDEM_SERVICO,
            COUNT(CASE WHEN STATUS = 1 THEN 1 END) AS ABERTO,
            COUNT(CASE WHEN STATUS = 2 THEN 2 END) AS EM_ANDAMENTO,
            COUNT(CASE WHEN STATUS = 3 THEN 3 END) AS CONCLUIDO,
            COUNT(CASE WHEN STATUS = 4 THEN 4 END) AS CANCELADO
FROM ORDENS_SERVICOS OS
GO


