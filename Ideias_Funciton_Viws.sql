-- view que vai trazer todo o faturamento total em um periodo determinado
CREATE FUNCTION dbo.FN_FATURAMENTO_PERIODO
(
    @DataInicio DATE,
    @DataFim    DATE
)
RETURNS DECIMAL(12,2)
AS
BEGIN
    DECLARE @total DECIMAL(12,2);

    SELECT @total = ISNULL(SUM(VALOR), 0)
    FROM   ORDENS_SERVICOS
    WHERE  STATUS = 3   -- somente OS concluídas
      AND  (@DataInicio IS NULL OR COALESCE(DATA_EXECUCAO, DATA_ABERTURA) >= @DataInicio)
      AND  (@DataFim    IS NULL OR COALESCE(DATA_EXECUCAO, DATA_ABERTURA) <= @DataFim);

    RETURN @total;
END
GO

