--TIPO-VARIAVEL
-- Total liquido de uma OS: soma de (QTD * VALOR - DESCONTO) dos servicos
CREATE FUNCTION FC_TOTAL_OS (@COD_OS INT)
RETURNS DECIMAL(10,2)
AS
BEGIN
    DECLARE @total DECIMAL(10,2);
 
    SELECT @total = SUM(QTD * VALOR - DESCONTO)
    FROM SERVICOS_REALIZADOS
    WHERE OS_COD = @COD_OS;
 
    RETURN ISNULL(@total, 0);
END
GO

-- Consultar Todos os Contratos, e seus equipamentos, atraves do nome do cliente, traga todas as informaçoes de contrato, do equipamento
--e os dados dos clientes, a busca tem que ser feita atraves do nome do cliente, TIPO TABELA

CREATE FUNCTION FC_CONTRATOS_CLIENTES (@NOME VARCHAR(100))
RETURNS TABLE
AS
RETURN
(
    SELECT
        -- dados do contrato
        C.COD_CONTRATO,
        C.TIPO_CONTRATO,
        C.DESCRICAO         AS DESCRICAO_CONTRATO,
        C.DATA_INICIO,
        C.DATA_FIM,
        C.OBS               AS OBS_CONTRATO,
        -- dados da pessoa
        P.COD_PESSOA,
        P.NOME,
        P.ENDERECO,
        P.NUMERO,
        P.CEP,
        P.CIDADE,
        P.ESTADO,
        P.TELEFONE,
        P.EMAIL,
        CASE WHEN C.COD_PESSOA_FISICA IS NOT NULL THEN 'FISICA' ELSE 'JURIDICA' END AS TIPO_PESSOA,
        PF.CPF,
        PF.RG,
        PF.DATA_NASCIMENTO,
        PJ.CNPJ,
        PJ.RAZAO_SOCIAL,
        -- equipamentos do contrato
        E.COD_EQUIPAMENTO,
        E.MARCA,
        E.MODELO,
        E.BTUS,
        CE.QTD              AS QTD_EQUIPAMENTO
    FROM CONTRATOS C
    INNER JOIN PESSOAS P                ON P.COD_PESSOA = COALESCE(C.COD_PESSOA_FISICA, C.COD_PESSOA_JURIDICA)
    LEFT JOIN PESSOAS_FISICAS PF        ON PF.PESSOA_FISICA_COD = C.COD_PESSOA_FISICA
    LEFT JOIN PESSOAS_JURIDICAS PJ      ON PJ.PESSOA_JURIDICA_COD = C.COD_PESSOA_JURIDICA
    LEFT JOIN CONTRATOS_EQUIPAMENTOS CE ON CE.CONTRATO_COD = C.COD_CONTRATO
    LEFT JOIN EQUIPAMENTOS E            ON E.COD_EQUIPAMENTO = CE.EQUIPAMENTO_COD
    WHERE P.NOME LIKE '%' + @NOME + '%'
)
GO

