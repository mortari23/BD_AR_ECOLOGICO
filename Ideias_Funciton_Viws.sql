--Consultar Todas as ordens de serviços e seus respectivos serviços efetuados

CREATE VIEW VW_OS_SERVICOS_REALIZADOS
AS
SELECT
    OS.COD_OS,
    OS.TIPO_OS,
    CASE OS.STATUS
        WHEN 1 THEN 'ABERTA'
        WHEN 2 THEN 'EM ANDAMENTO'
        WHEN 3 THEN 'CONCLUIDA'
    END                             AS STATUS_DESCRICAO,
    OS.DATA_ABERTURA,
    OS.DATA_EXECUCAO,
    OS.DESCRICAO_PROBLEMA,
    OS.DESCRICAO_EXECUTADO,
    S.COD_SERVICO,
    S.DESCRICAO                     AS DESCRICAO_SERVICO,
    SR.QTD,
    SR.VALOR                        AS VALOR_UNITARIO,
    SR.QTD * SR.VALOR               AS VALOR_BRUTO,
    SR.DESCONTO,
    (SR.QTD * SR.VALOR) - SR.DESCONTO AS VALOR_LIQUIDO,
    SR.OBS                          AS OBS_SERVICO
FROM ORDENS_SERVICOS OS
INNER JOIN SERVICOS_REALIZADOS SR    ON SR.OS_COD = OS.COD_OS
INNER JOIN SERVICOS S                ON S.COD_SERVICO = SR.SERVICO_COD
GO

