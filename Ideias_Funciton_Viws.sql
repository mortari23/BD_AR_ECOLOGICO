            COUNT(CASE WHEN STATUS = 2 THEN 'EM_ANDAMENTO' END)  AS EM_ANDAMENTO,
            COUNT(CASE WHEN STATUS = 3 THEN 'CONCLUIDO' END)     AS CONCLUIDAS,
            COUNT(CASE WHEN STATUS = 4 THEN 'CANCELADO' END)     AS CANCELADAS
FROM ORDENS_SERVICOS OS
GO

